function withOpacity(variableName, defaultAlpha = 1) {
  return ({ opacityValue }) => {
    if (opacityValue !== undefined) {
      return `rgba(var(${variableName}), ${opacityValue})`;
    }
    return `rgba(var(${variableName}), ${defaultAlpha})`;
  };
}

